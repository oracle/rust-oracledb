use std::collections::HashMap;

use oracledb::{JsonValue, OracleNumber};

mod common;

fn main() -> Result<(), oracledb::Error> {
    let config = common::get_sample_config()?;
    let connection = oracledb::connect(config)?;

    // check the Oracle Database version
    let version = connection.version()?;
    if version.0 < 23 {
        println!(
            "JSON Duality Views require Oracle AI Database 26ai or later."
        );
        return Ok(());
    }

    connection.execute("drop view if exists rso_examples_books_dv", &[])?;
    let _author_guard = common::create_table(
        &connection,
        "rso_examples_authors",
        r#"
        id number generated by default on null as identity primary key,
        name varchar2(100)
        "#,
    )?;

    let _book_guard = common::create_table(
        &connection,
        "rso_example_books",
        r#"
        id number generated by default on null as identity primary key,
        title varchar2(100),
        author_id number references rso_examples_authors (Id)
        "#,
    )?;

    println!("Creating duality view...");
    connection.execute(
        r#"
        create or replace json relational duality view rso_examples_books_dv as
        select json {
            '_id'        : b.id,
            'book_title' : b.title,
            'author'     :
            (
                select json {
                    'author_id'   : a.id,
                    'author_name' : a.name
                }
                from rso_examples_authors a
                with insert update
                where a.id = b.author_id
            )
        }
        from rso_example_books b
        with insert update delete
        "#,
        &[],
    )?;

    println!("Inserting JSON document...");
    let mut author = HashMap::new();
    author.insert(
        "author_id".to_string(),
        JsonValue::Number(OracleNumber::from(2000)),
    );
    author.insert(
        "author_name".to_string(),
        JsonValue::String("John Doe".to_string()),
    );

    let mut book = HashMap::new();
    book.insert(
        "_id".to_string(),
        JsonValue::Number(OracleNumber::from(1000)),
    );
    book.insert(
        "book_title".to_string(),
        JsonValue::String("My New Book".to_string()),
    );
    book.insert("author".to_string(), JsonValue::JsonObject(author));

    let json_doc = JsonValue::JsonObject(book);

    connection.execute(
        "insert into rso_examples_books_dv (data) values (:1)",
        &[&json_doc],
    )?;

    connection.commit()?;

    println!("Querying...");
    let row = connection.query_row(
        r#"
        select data
        from rso_examples_books_dv b
        where json_value(b.data, '$."_id"' returning number) = :1
        "#,
        &[&1000],
    )?;

    let fetched_doc: JsonValue = row.get(0)?;
    println!("{fetched_doc:#?}");

    Ok(())
}
